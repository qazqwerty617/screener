function renderSitemap() {
  const urls = [{ path: "/", priority: "1.0", changefreq: "daily" }, ...PAGES.map(page => ({
    path: page.path,
    priority: page.secondary ? "0.4" : "0.8",
    changefreq: page.secondary ? "monthly" : "weekly",
  }))];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(url => `  <url><loc>${SITE_ORIGIN}${url.path}</loc><lastmod>${LAST_MODIFIED}</lastmod><changefreq>${url.changefreq}</changefreq><priority>${url.priority}</priority></url>`).join("\n")}\n</urlset>\n`;
}

